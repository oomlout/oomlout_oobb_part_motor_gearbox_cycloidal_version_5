"""Portable exports alongside the normal working_scad catalogue output."""

import copy
import json
from pathlib import Path
import shutil
import subprocess
import oobb
import opsc
from solid2 import scad_render
from gearbox.parts import (
    blank,
    cylinder,
    hole,
    seat,
    through,
    group,
    resolve,
    coupling_nut_pockets,
    motor_mount,
)
from gearbox.hardware import hardware_list, export_fasteners


def write(path, content):
    Path(path).write_text(content, encoding="utf-8")


def render(t, mode="3dpr"):
    return scad_render(opsc.opsc_get_object(copy.deepcopy(t["components"]), mode=mode))


def fit_coupons(c):
    # Three small seats for each small bearing; output bearing gets a shallow ring.
    tests = {}
    for key in ("eccentric", "shaft", "output"):
        spec = c[key + "_bearing"]
        t = blank()
        depth = spec["depth"] + 2
        for i, clearance in enumerate((0, 0.1, 0.2)):
            trial = blank()
            cylinder(trial, spec["od"] / 2 + 2, depth)
            hole(trial, spec["od"] / 2 - 1.5, depth)
            seat(
                trial, c["bearing_" + key], spec, depth, clearance, c["bearing_endplay"]
            )
            group(t, trial, [(i - 1) * (spec["od"] + 6), 0, 0])
        tests["fit_" + key + "_bearings"] = (t, 3)
    t = blank()
    cylinder(t, 8, 8)
    through(t, [[0, 0]], 8, size="m5")
    tests["fit_m5_axle"] = (t, 1)
    t = blank()
    for i, clearance in enumerate((0, 0.1, 0.2)):
        track = blank()
        radius = c["guide_bearing"]["od"] / 2 + c["radius_offset"] + clearance
        cylinder(track, radius + 3, c["rotor_thickness"])
        hole(track, radius, c["rotor_thickness"])
        group(t, track, [(i - 1) * 30, 0, 0])
    tests["fit_guide_tracks"] = (t, 3)
    journals = blank()
    for row, key in enumerate(("eccentric", "shaft")):
        for i, clearance in enumerate((0, 0.1, 0.2)):
            trial = blank()
            cylinder(trial, c[key + "_bearing"]["id"] / 2 - clearance, 6)
            through(trial, [[0, 0]], 6, size="m5")
            group(journals, trial, [(i - 1) * 36, row * 36, 0])
    tests["fit_journals"] = (journals, 6)
    t = blank()
    from gearbox.parts import add

    add(
        t,
        "oobb_plate",
        width=3,
        height=3,
        depth=c["motor_plate_depth"],
        pos=[0, 0, 0],
        holes=False,
    )
    hole(
        t,
        c["motor_pilot_diameter"] / 2 + c["motor_pilot_clearance"],
        c["motor_plate_depth"],
    )
    through(t, c["motor_positions"], c["motor_plate_depth"], countersink=True)
    tests["fit_nema17_mount"] = (t, 1)
    t = blank()
    # Exact production slice: motor opening plus the above-face nut pockets
    # and their retaining roofs, rather than a generic square-hole gauge.
    group(t, motor_mount(**c), [0, 0, c["mount_bottom_z"] + 3])
    add(t, "oobb_cube", "n", [0, 0, -100], size=[200, 200, 100], zz="bottom")
    add(
        t,
        "oobb_cube",
        "n",
        [0, 0, c["rear_support_top"] + 3],
        size=[200, 200, 100],
        zz="bottom",
    )
    tests["fit_motor_skirt"] = (t, 1)
    flange = blank()
    coupon_bottom = c["drive_roof_z"] - 1
    coupon_depth = c["drive_end"] - coupon_bottom
    cylinder(
        flange, c["drive_journal_radius"], coupon_depth, xy=(-c["radius_offset"], 0)
    )
    hole(
        flange,
        c["coupling_barrel_diameter"] / 2 + c["drive_cavity_clearance"],
        coupon_depth,
    )
    through(flange, c["coupling_positions"], coupon_depth)
    coupling_nut_pockets(flange, c, c["drive_roof_top"] - coupon_bottom)
    tests["fit_coupling_flange"] = (flange, 1)
    return tests


def export_gearbox(folder, model, save_type="none"):
    if (Path(folder) / "SEALED.json").exists():
        raise ValueError(f"Sealed release cannot be regenerated: {folder}")
    if model["config"].get("architecture") == "captured_6810":
        from gearbox.captured_export import export_gearbox as captured_export

        return captured_export(folder, model, save_type)
    folder = Path(folder)
    if (folder / "SEALED.json").exists():
        raise ValueError(f"Sealed release cannot be regenerated: {folder}")
    folder.mkdir(parents=True, exist_ok=True)
    # Obsolete joint coupons belong to the preserved pre-compact snapshot.
    for old in ("fit_hub_key", "fit_m6_hub_bolt", "fit_606_tracks"):
        for suffix in (".scad", ".stl"):
            (folder / (old + suffix)).unlink(missing_ok=True)
    c = model["config"]
    pieces = model["pieces"]
    lengths = export_fasteners(folder, c)
    for name, p in pieces.items():
        write(
            folder / f"{name}.scad",
            f'// Generated by working_scad; edit Python builders/populate options.\n$fn=96;\nmodule {name}() {{\n{render(p["thing"])}\n}}\n{name}();\n',
        )
    uses = "".join(f"use <{name}.scad>\n" for name in pieces)
    layout = uses + "\n$fn=96;\n"
    for item in model["layout"]:
        layout += f'translate({json.dumps(item["pos"])}) {item["part"]}();\n'
    write(
        folder / "3dpr.scad",
        f"// Print one of each of the {len(pieces)} pieces; all on z=0.\n" + layout,
    )
    coupons = fit_coupons(c)
    for name, (t, _) in coupons.items():
        write(
            folder / f"{name}.scad",
            "// Optional test print. Bearing seats left to right: radial allowance 0, 0.10, 0.20 mm.\n$fn=96;\n"
            + render(t),
        )
    assignments = "\n".join(
        f"{k} = {json.dumps(v)};"
        for k, v in {
            **{
                k: c[k]
                for k in (
                    "drive_start",
                    "mount_bottom_z",
                    "cap_screw_head_z",
                    "guide_bolt_head_z",
                    "guide_bearing_z",
                    "guide_spacer_z",
                    "guide_nut_rotations",
                    "case_nut_bottom",
                    "casing_bottom_z",
                    "hub_upper_start",
                    "hub_upper_end",
                    "coupling_positions",
                    "coupling_nut_rotations",
                    "coupling_nut_hex_rotation",
                    "coupling_flange_z",
                    "drive_roof_top",
                    "coupling_grub_z",
                    "coupling_grub_angles",
                    "coupling_service_angle",
                )
            },
            "coupling_barrel_radius": c["coupling_barrel_diameter"] / 2,
            "ratio": c["reduction"],
            "eccentricity": c["radius_offset"],
            "H": c["housing_depth"],
            "flange_depth": c["flange_depth"],
            "rotor_depth": c["rotor_thickness"],
            "rotor_z": [c["rotor_a_z"], c["rotor_b_z"]],
            "eccentric_bearing_z": c["eccentric_bearing_z"],
            "shaft_bearing_z": c["shaft_bearing_z"],
            "output_bearing_z": c["output_bearing_z"],
            "housing_positions": c["housing_positions"],
            "motor_positions": c["motor_positions"],
            "guide_positions": c["guide_positions"],
            "motor_face": c["motor_face_z"],
            "motor_plate_depth": c["motor_plate_depth"],
            "coupling_z": c["coupling_z"],
            "coupling_depth": c["coupling_length"],
            "coupling_radius": c["coupling_diameter"] / 2,
            "retainer_depth": c["front_retainer_depth"],
            "rear_retainer_depth": c["rear_retainer_depth"],
            "guide_nut_bottom": c["guide_nut_bottom"],
            "nut_depth_m3": oobb.gv("nut_depth_m3", "true"),
            "front_journal_bottom": c["front_journal_bottom"],
            "eccentric_bearing_depth": c["eccentric_bearing"]["depth"],
        }.items()
    )
    write(
        folder / "assembly.scad",
        uses
        + "use <hardware.scad>\n"
        + assignments
        + "\n"
        + Path(__file__).with_name("assembly.scad.template").read_text(),
    )
    from gearbox.animation import view_settings

    view = view_settings(c)
    camera = f'$vpt = {json.dumps(view["target"])};\n$vpr = {json.dumps(view["rotation"])};\n$vpd = {view["distance"]};\n'
    write(
        folder / "animation.scad",
        f'// View > Animate: FPS 12, Steps 192. Set explode=0 to assemble.\ninput_turns = {c["reduction"]}*$t;\nexplode = {view["explode"]};\n'
        + camera
        + "include <assembly.scad>\n",
    )
    from gearbox.annotations import export_annotations

    annotated = export_annotations(folder, c)
    annotation_camera = f'$vpt = {json.dumps(annotated["target"])};\n$vpr = {json.dumps(annotated["rotation"])};\n$vpd = {annotated["distance"]};\n'
    write(
        folder / "exploded.scad",
        f'explode = {view["explode"]};\n'
        + annotation_camera
        + "include <assembly.scad>\ninclude <exploded_labels.scad>\n",
    )
    write(
        folder / "fit_check.scad",
        f'// Empty render = no collision at this pose.\nfit_only = true;\ninput_turns = {c["reduction"]}*$t;\ninclude <assembly.scad>\n',
    )
    write(
        folder / "installation_check.scad",
        "// Slide the internal stack through the constant-section stator. Empty = clear.\ninstallation_shift = 0;\ninput_turns = 0.173;\ninclude <assembly.scad>\n",
    )
    for name in (
        "rear_bearing",
        "casing",
        "coupling",
        "upper_disc",
        "guide_bolt",
        "guide_bearing",
    ):
        write(
            folder / f"{name}_installation_check.scad",
            f"// Lower onto the integrated motor faceplate before fitting discs.\n{name}_installation_shift=0;\ninclude <assembly.scad>\n",
        )
    write(folder / "section.scad", "cutaway = true;\ninclude <assembly.scad>\n")
    write(
        folder / "motion.scad",
        f'// Assembled cutaway: fixed blue supports, rotating orange casing.\ninput_turns = {c["reduction"]}*$t;\ncutaway = true;\ninclude <assembly.scad>\n',
    )
    write(
        folder / "motor_drive.scad",
        "// Compact motor interface, actual production parts.\ndrive_only = true;\ncutaway = true;\ninclude <assembly.scad>\n",
    )
    write(
        folder / "guide_rollers.scad",
        f"// Bearings remain on fixed M6 axes while the discs orbit around them.\nguide_only=true;\ninput_turns=$t;\n$vpt=[0,0,{c['housing_depth']/2}];\n$vpr=[65,0,25];\n$vpd=260;\ninclude <assembly.scad>\n",
    )
    write(
        folder / "grub_access_check.scad",
        f"// Assembly stage: tighten both grub screws before pin supports and casing are installed.\ngrub_access_check=true;\ninput_turns={c['coupling_service_angle']/360};\ninclude <assembly.scad>\n",
    )
    write(
        folder / "grub_access.scad",
        f"// Tighten both grub screws at this stage, before disc B and the casing.\ngrub_access_view=true;\ninput_turns={c['coupling_service_angle']/360};\n$vpt=[0,0,12];\n$vpr=[65,0,25];\n$vpd=220;\ninclude <assembly.scad>\n",
    )
    write(
        folder / "bearing_installation_check.scad",
        "// Lower bearing inserts from below; upper bearing slides down over the installed flange.\nbearing_installation_shift=0;\ninclude <assembly.scad>\n",
    )
    write(
        folder / "joint_installation_check.scad",
        "// Lower the front bearing cap onto the flange-up coupler.\njoint_installation_shift=0;\ninclude <assembly.scad>\n",
    )
    write(
        folder / "nut_installation_check.scad",
        "// Load guide nuts from below before the motor.\nnut_installation_shift=0;\ninclude <assembly.scad>\n",
    )
    write(
        folder / "nut_loading.scad",
        "// Underside nut pockets; fit these nuts before the motor.\nnut_loading_view=true;\n$vpr=[120,0,25];\ninclude <assembly.scad>\n",
    )
    write(
        folder / "flange_nut_installation_check.scad",
        "// Continuous sweep of both nuts straight inward from outside the hub; empty means clear.\nflange_nut_installation_check=true;\ninclude <assembly.scad>\n",
    )
    write(
        folder / "flange_nut_loading.scad",
        "// Nuts slide inward along the outward-facing side slots before the screws are fitted.\nflange_nut_loading_view=true;\ninclude <assembly.scad>\n",
    )
    manifest = dict(
        schema=3,
        reduction=c["reduction"],
        parameters=c,
        pieces={
            n: {k: v for k, v in p.items() if k != "thing"} for n, p in pieces.items()
        },
        kinematics=dict(
            output_member="outer_casing",
            disc_lobes=c["disc_lobes"],
            casing_contacts=c["ring_pin_count"],
            input_turns_per_output_turn=c["reduction"],
            output_direction="same_as_input",
            fixed_members=["motor_mount", "pin_front", "guide_bearing_centres"],
            eccentric_phase_degrees=[0, 180],
            disc_profile_phase_degrees=c["disc_phase_degrees"],
        ),
        print_layout=model["layout"],
        hardware=hardware_list(c),
        preview_screw_lengths_mm=lengths,
        fit_coupons={n: count for n, (_, count) in coupons.items()},
        preview_hardware_counts=dict(
            countersunk_screws=8,
            guide_hex_bolts=c["guide_pin_count"],
            nuts_m3=4 + len(c["coupling_positions"]),
            nuts_m6=c["guide_pin_count"],
            shaft_washers=0,
            guide_race_spacers=3 * c["guide_pin_count"],
            hub_joining_bolts=0,
            flange_screws=len(c["coupling_positions"]),
            bearings=5 + 2 * c["guide_pin_count"],
            hub_set_screws=0,
            couplings=1,
            motors=1,
            coupling_set_screws=2,
        ),
    )
    write(folder / "gearbox.json", json.dumps(manifest, indent=2) + "\n")
    if save_type != "none":
        executable = shutil.which("openscad.com") or shutil.which("openscad")
        if not executable:
            raise RuntimeError("OpenSCAD required for STL generation")
        for name in [*pieces, "3dpr", *coupons]:
            result = subprocess.run(
                [
                    executable,
                    "--backend=Manifold",
                    "-o",
                    str(folder / f"{name}.stl"),
                    str(folder / f"{name}.scad"),
                ],
                capture_output=True,
                text=True,
            )
            if (
                result.returncode
                or "ERROR:" in result.stderr
                or "WARNING:" in result.stderr
            ):
                raise RuntimeError(result.stderr)
    write(
        folder / "README.md",
        f"""# Version 4: compact flange-up {c['reduction']}:1 gearbox

Generated through working_oomp_populate -> working_oomp -> working_scad.
Edit the Python builders/populate overrides, then regenerate.

The {c['coupling_diameter']:g} mm flange faces UP at the {c['motor_shaft_length']:g} mm motor shaft tip.
The front cover is {c['housing_depth']+c['front_retainer_depth']:g} mm above the motor face.
Disc gap is {c['disc_gap']:g} mm. The rear {c['bearing_output']} wraps around the top of the motor.

Eight printed pieces remain. eccentric_hub_lower is now ONE hollow shaft carrying both
eccentrics; eccentric_hub_upper is its separate front bearing cap. The old central M6
joining bolt, nut, washer and D-key joint are eliminated. Two M3x{c['coupling_screw_length']:g} screws
through the cap and flange fasten into the two side-loaded M3 shaft nuts.

Bearings: 12 x {c['bearing_guide']} guide rollers, 2 x {c['bearing_eccentric']} eccentric bearings,
1 x {c['bearing_shaft']} front shaft bearing, 2 x {c['bearing_output']} casing bearings.
The larger eccentric bores let the upper bearing pass over the installed flange.
Both discs retain six oversized rolling tracks: bearings remain on the fixed M6 axes.

Guide bolts: six M6x{lengths['guide']:g} partially threaded hex bolts. Their shanks must be smooth
for at least {c['guide_bolt_head_z']-c['guide_bearing_z'][0]+c['guide_bearing']['depth']/2:g} mm below the heads.
Per bolt: steel {2*c['guide_spacer_radius']:g} OD / {2*c['guide_spacer_bore']:g} ID inner-race spacers, lengths
{' / '.join(f'{v:g}' for v in c['guide_spacer_depths'])} mm, with a {c['bearing_guide']} between each pair.
Guide heads nest inside the output-bearing bore when guide_heads_nested is true.
Guide nuts load from below before fitting the motor; their bottom is {c['guide_nut_bottom']:g} mm
relative to the motor face. Bolt tips clear the motor sides.
Casing: four M3x{lengths['housing']:g} countersunk bolts/nuts. Motor: four M3x{lengths['motor']:g} countersunk screws.

Assembly sequence:
1. Test the bearing seats, journals, {c['bearing_guide']} tracks, motor interface/skirt and coupling nut coupon.
2. Load the six M6 guide nuts from the bottom; attach the bracket to the motor.
3. Fit the rear {c['bearing_output']} and lower the empty casing onto it; casing nuts load from below first.
4. Preassemble disc A and its eccentric bearing onto the shaft FROM BELOW; put the
   six rear race spacers in place, then lower this unit over the motor shaft.
5. Insert the flange-up coupler through the hollow shaft from above. Its flange ends
   at the motor shaft tip. Tighten both grub screws through the shaft's radial holes,
   BEFORE fitting disc B, the upper eccentric bearing and the front cap.
   For tool access, leave the casing off or lift it temporarily.
6. Fit the six lower {c['bearing_guide']}s and middle spacers. Slide disc B down from above, keeping
   both disc index marks aligned. Its eccentric bearing also slides straight down
   over the flange. Add the upper {c['bearing_guide']}s and front race spacers.
7. Fit the front carrier and bearings, lower the bearing cap through the centre,
   and fit the two vertical M3 coupling screws from above. Fit the six M6 guide bolts.
8. Attach the output cover. Turn by hand before powering the motor.

3dpr.scad / .stl: all eight printed parts; individual SCAD/STL files are also provided.
animation.scad / .gif / .mp4: exploded motion with all hardware (12 FPS, 192 steps).
exploded.scad / .png and part_names.md: annotated identifiers and hardware.
grub_access.scad / .png: actual pre-disc-B tool access stage.
motor_drive.scad: compact shaft/coupler cross-section. guide_rollers.scad: roller mechanism.
fit_*.scad / .stl: interface coupons. *_installation_check.scad: actual assembly paths.
validation.json and animation_render.json record the rendered checks and source hashes.
A supplementary motion_validation.json records the full 73-pose sweep when run separately.

The motor preview assumes {c['motor_body_width']:g} mm square, {c['motor_body_depth']:g} mm long body and
{c['motor_shaft_length']:g} mm shaft. The skirt opening has {c['motor_body_clearance']:g} mm side clearance.
Check motor-specific wires, plugs and front-face features with the skirt coupon.
Geometry checks do not establish printed fit, load capacity or durability.
""",
    )
    if c.get("render_animation", False):
        from gearbox.animation import render_animation

        render_animation(folder, **c)
